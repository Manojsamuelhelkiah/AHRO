import { expect, test } from '@playwright/test';

test('base planning with pending customization commits without files and fences delayed failed uploads', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: /Demo Reviewer/ }).click();
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await expect(page.getByText('Agentic HRO Suite').first()).toBeVisible();
  await page.goto('/client-setup');
  await expect(page.getByPlaceholder('e.g. Acme Corp')).not.toHaveValue('');
  await page.getByRole('button', { name: /Next Step/ }).click();
  await page.getByRole('button', { name: /Next Step/ }).click();
  await expect(page.getByText('Process Adoption Mode', { exact: true })).toBeVisible();
  await page.locator('select[name="processMode"]').selectOption('custom');
  await expect(page.getByText(/No upload is required/)).toBeVisible();
  await page.getByRole('button', { name: /Confirm reviewed planning basis/ }).click();
  await page.getByRole('button', { name: /Next Step/ }).click();
  await page.getByRole('button', { name: /Run Readiness Rollup/ }).click();
  await expect(page.getByRole('button', { name: /Commit Implementation/ })).toBeEnabled();
  await page.getByRole('button', { name: /Commit Implementation/ }).click();
  await expect(page.getByText('Implementation Committed', { exact: true })).toBeVisible();
  await expect(page).toHaveURL(/scenarioId=\d+/);
  const scenarioId = Number(new URL(page.url()).searchParams.get('scenarioId'));
  const saved = await page.request.get(`/api/scenarios/${scenarioId}`);
  expect(saved.ok()).toBeTruthy();
  const snapshot = await saved.json();
  expect(snapshot.fileIds).toEqual([]);
  expect(snapshot.setupData.processMode).toBe('custom');
  expect(snapshot.setupData.flowBasis.source).toBe('product-base');
  expect(snapshot.setupData.customizationStatus).toBe('pending-review');
  await page.reload();
  await expect(page.getByText('Implementation Committed', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Effective planning flow source' })).toBeVisible();
  await expect(page.getByText(/Customization: Pending review/)).toBeVisible();
  await expect(page.getByText(/not launch approval/)).toBeVisible();
  await page.getByRole('button', { name: /Upload Customizations Later/ }).click();
  let releaseUpload!: () => void;
  const uploadDelay = new Promise<void>((resolve) => { releaseUpload = resolve; });
  await page.route('**/api/scenario-files/upload-intents', async (route) => {
    await uploadDelay;
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Upload temporarily unavailable' }) });
  });
  await page.locator('input[type="file"]').setInputFiles({ name: 'optional-customization.txt', mimeType: 'text/plain', buffer: Buffer.from('Fictional review note only.') });
  const onward = page.getByRole('button', { name: /Continue to Workspace/ });
  await expect(onward).toBeDisabled();
  releaseUpload();
  await expect(page.getByText(/Upload temporarily unavailable/)).toBeVisible();
  await expect(onward).toBeEnabled();
  await page.setViewportSize({ width: 402, height: 874 });
  await onward.scrollIntoViewIfNeeded();
  const size = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: innerWidth }));
  expect(size.scroll).toBeLessThanOrEqual(size.width + 1);
  await page.screenshot({ path: 'test-results/client-setup-base-mobile.png', fullPage: true });
  await onward.click();
  await expect(page).toHaveURL(/\/$/);
  const cleanup = await page.request.delete(`/api/scenarios/${scenarioId}`);
  expect(cleanup.ok()).toBeTruthy();
});
